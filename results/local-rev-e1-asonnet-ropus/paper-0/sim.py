"""
Agent-based simulation of opinion dynamics under recommender-system feedback loops.

Models a population of N agents with scalar opinions in [-1, 1], a content pool
generated by the agents themselves (user-generated content), and a recommender
that selects k items per agent per round under one of several policies:
  - random:      uniformly random recommendations (no personalization)
  - engagement:  pure engagement-maximizing (nearest-opinion content; "filter bubble")
  - diversity:   epsilon-greedy mix of engagement-maximizing + randomly diverse picks

Agents probabilistically "engage" with recommended items (probability decays with
opinion distance). Engaged items update the agent's opinion via a bounded-confidence
rule (assimilation if within a tolerance window, small-probability "backfire"/reactance
moving the agent further away otherwise). New content is periodically posted by a
random subset of agents at their current opinion, closing the feedback loop between
population opinions and the content pool the recommender draws from.

Outputs: per-round polarization (opinion variance, extremism share), engagement rate,
and content diversity consumed, aggregated over multiple random seeds.
"""
import numpy as np
import json
import time

RNG_SEED_BASE = 12345


def run_simulation(
    policy="engagement",
    N=300,
    M_cap=3000,
    T=150,
    k=5,
    confidence_bound=0.5,
    mu=0.15,
    backfire_prob=0.15,
    backfire_rate=0.10,
    engagement_sigma=0.4,
    base_engage_rate=0.9,
    post_frac=0.05,
    epsilon=0.3,
    seed=0,
):
    rng = np.random.default_rng(RNG_SEED_BASE + seed)

    opinions = rng.uniform(-1, 1, size=N)
    pool = rng.uniform(-1, 1, size=min(M_cap, N * 3))

    history = {
        "variance": [],
        "extremism": [],
        "engagement_rate": [],
        "diversity_consumed": [],
    }

    for t in range(T):
        dist_matrix = np.abs(opinions[:, None] - pool[None, :])  # N x M

        if policy == "random":
            idx = rng.integers(0, len(pool), size=(N, k))
        elif policy == "engagement":
            idx = np.argsort(dist_matrix, axis=1)[:, :k]
        elif policy == "diversity":
            close_k = max(1, int(round(k * (1 - epsilon))))
            div_k = k - close_k
            close_idx = np.argsort(dist_matrix, axis=1)[:, :close_k]
            if div_k > 0:
                div_idx = rng.integers(0, len(pool), size=(N, div_k))
                idx = np.concatenate([close_idx, div_idx], axis=1)
            else:
                idx = close_idx
        else:
            raise ValueError(policy)

        rec_items = pool[idx]  # N x k
        rec_dist = np.abs(opinions[:, None] - rec_items)

        engage_prob = base_engage_rate * np.exp(-(rec_dist ** 2) / (2 * engagement_sigma ** 2))
        engaged = rng.random(size=rec_dist.shape) < engage_prob  # N x k boolean

        n_engaged_per_agent = engaged.sum(axis=1)
        total_possible = N * k
        engagement_rate = engaged.sum() / total_possible

        consumed_dists = rec_dist[engaged]
        diversity_consumed = consumed_dists.mean() if consumed_dists.size > 0 else 0.0

        delta = np.zeros(N)
        for j in range(k):
            eng_j = engaged[:, j]
            item_op = rec_items[:, j]
            d = item_op - opinions
            within = np.abs(d) <= confidence_bound
            assimilate_mask = eng_j & within
            delta[assimilate_mask] += mu * d[assimilate_mask]

            outside = eng_j & (~within)
            backfire_roll = rng.random(N) < backfire_prob
            backfire_mask = outside & backfire_roll
            delta[backfire_mask] -= backfire_rate * d[backfire_mask]

        opinions = np.clip(opinions + delta, -1, 1)

        posters = rng.random(N) < post_frac
        new_items = opinions[posters]
        if new_items.size > 0:
            pool = np.concatenate([pool, new_items])
            if len(pool) > M_cap:
                pool = pool[-M_cap:]

        history["variance"].append(float(np.var(opinions)))
        history["extremism"].append(float(np.mean(np.abs(opinions) > 0.7)))
        history["engagement_rate"].append(float(engagement_rate))
        history["diversity_consumed"].append(float(diversity_consumed))

    return history, opinions


def summarize(history, last_frac=0.2):
    n = len(history["variance"])
    tail = max(1, int(n * last_frac))
    out = {}
    for key in history:
        arr = np.array(history[key][-tail:])
        out[key + "_final_mean"] = float(arr.mean())
    out["variance_initial"] = history["variance"][0]
    out["variance_trajectory"] = history["variance"]
    return out


def main():
    t0 = time.time()
    results = {}

    # --- Main policy comparison ---
    policies = ["random", "engagement", "diversity"]
    n_seeds = 8
    policy_results = {}
    for pol in policies:
        seed_summaries = []
        for s in range(n_seeds):
            hist, final_op = run_simulation(policy=pol, seed=s)
            seed_summaries.append(summarize(hist))
        agg = {}
        for key in ["variance_final_mean", "extremism_final_mean",
                    "engagement_rate_final_mean", "diversity_consumed_final_mean"]:
            vals = [s[key] for s in seed_summaries]
            agg[key + "_avg"] = float(np.mean(vals))
            agg[key + "_std"] = float(np.std(vals))
        agg["variance_trajectory_example"] = seed_summaries[0]["variance_trajectory"]
        policy_results[pol] = agg
        print(f"[policy comparison] {pol}: done ({time.time()-t0:.1f}s elapsed)")
    results["policy_comparison"] = policy_results

    # --- Ablation: confidence_bound (open-mindedness) under engagement policy ---
    cb_results = {}
    for cb in [0.2, 0.5, 0.8]:
        seed_summaries = []
        for s in range(5):
            hist, final_op = run_simulation(policy="engagement", confidence_bound=cb, seed=s)
            seed_summaries.append(summarize(hist))
        vals_var = [s["variance_final_mean"] for s in seed_summaries]
        vals_ext = [s["extremism_final_mean"] for s in seed_summaries]
        cb_results[str(cb)] = {
            "variance_avg": float(np.mean(vals_var)),
            "variance_std": float(np.std(vals_var)),
            "extremism_avg": float(np.mean(vals_ext)),
            "extremism_std": float(np.std(vals_ext)),
        }
        print(f"[confidence_bound ablation] cb={cb}: done ({time.time()-t0:.1f}s elapsed)")
    results["confidence_bound_ablation"] = cb_results

    # --- Ablation: epsilon sweep for diversity policy ---
    eps_results = {}
    for eps in [0.0, 0.2, 0.5, 1.0]:
        seed_summaries = []
        for s in range(5):
            hist, final_op = run_simulation(policy="diversity", epsilon=eps, seed=s)
            seed_summaries.append(summarize(hist))
        vals_var = [s["variance_final_mean"] for s in seed_summaries]
        vals_eng = [s["engagement_rate_final_mean"] for s in seed_summaries]
        eps_results[str(eps)] = {
            "variance_avg": float(np.mean(vals_var)),
            "variance_std": float(np.std(vals_var)),
            "engagement_rate_avg": float(np.mean(vals_eng)),
            "engagement_rate_std": float(np.std(vals_eng)),
        }
        print(f"[epsilon sweep] eps={eps}: done ({time.time()-t0:.1f}s elapsed)")
    results["epsilon_sweep"] = eps_results

    results["total_runtime_sec"] = time.time() - t0
    with open("results.json", "w") as f:
        json.dump(results, f, indent=2)
    print(f"Total runtime: {time.time()-t0:.1f}s")
    print("Saved results.json")


if __name__ == "__main__":
    main()
